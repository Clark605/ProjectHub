/// Canonical layout width breakpoints across ProjectHub.
class Breakpoints {
  Breakpoints._();

  /// Minimum content constraint (300px).
  static const double minContent = 300.0;

  /// Narrow mobile constraint (400px).
  static const double narrow = 400.0;

  /// Standard compact/mobile boundary (600px).
  static const double compact = 600.0;

  /// Standard mobile-to-tablet breakpoint (768px).
  static const double mobile = 768.0;

  /// Tablet-to-desktop or wide layout breakpoint (900px).
  static const double tablet = 900.0;

  /// Wide content/metrics grid breakpoint (1100px).
  static const double wide = 1100.0;

  /// Standard desktop breakpoint (1200px).
  static const double desktop = 1200.0;
}
