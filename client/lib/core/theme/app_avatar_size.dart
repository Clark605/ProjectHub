/// Standard semantic avatar size tokens across ProjectHub.
class AppAvatarSize {
  AppAvatarSize._();

  /// 20px — Extra small avatar.
  static const double xs = 20.0;

  /// 24px — Small avatar used in task cards, compact lists, and dense footers.
  static const double sm = 24.0;

  /// 28px — Compact avatar used in presence sheets, comments, and activity tiles.
  static const double compact = 28.0;

  /// 32px — Standard medium avatar used in user profiles and navigation bars.
  static const double md = 32.0;

  /// 40px — Large avatar used in member tiles and list items.
  static const double lg = 40.0;

  /// 56px — Extra large avatar used in detail screens and profiles.
  static const double xl = 56.0;
}

